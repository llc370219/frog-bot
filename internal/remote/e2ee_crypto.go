const (
	e2eeHKDFSalt = "frog-e2ee-v1"
)

// E2EEClientOptions holds parsed fields from a `froge2ee://` pairing URI.
// Format:
//   froge2ee://<peer_id>:<psk_b64url>@<host_id>?relay=<wss_url>&pub=<host_x25519_pub_b64url>[&lan=<ip:port>][&rt=<relay_token>]#<server_name>
type E2EEClientOptions struct {
	PeerIDHex    string
	PeerPSKHex   string
	HostID       string
	ServerPubB64 string
	RelayURL     string
	RelayToken   string
	LANAddr      string
	ServerName   string
}

// BuildE2EEURI constructs a compact QR-friendly `froge2ee://` URI.
func BuildE2EEURI(opts E2EEClientOptions) string {
	pskToken := opts.PeerPSKHex
	if raw, err := hex.DecodeString(opts.PeerPSKHex); err == nil && len(raw) == 32 {
		pskToken = base64.RawURLEncoding.EncodeToString(raw)
	}
	q := url.Values{}
	if r := strings.TrimSpace(opts.RelayURL); r != "" {
		q.Set("relay", r)
	}
	if p := strings.TrimSpace(opts.ServerPubB64); p != "" {
		q.Set("pub", p)
	}
	if lan := strings.TrimSpace(opts.LANAddr); lan != "" {
		q.Set("lan", lan)
	}
	if rt := strings.TrimSpace(opts.RelayToken); rt != "" {
		q.Set("rt", rt)
	}
	u := &url.URL{
		Scheme:   "froge2ee",
		User:     url.UserPassword(opts.PeerIDHex, pskToken),
		Host:     opts.HostID,
		RawQuery: q.Encode(),
		Fragment: opts.ServerName,
	}
	return u.String()
}

// ParseE2EEURI parses a `froge2ee://` URI generated by a Frog Bot host.
func ParseE2EEURI(raw string) (E2EEClientOptions, error) {
	s := strings.TrimSpace(raw)
	if idx := strings.Index(strings.ToLower(s), "froge2ee://"); idx >= 0 {
		s = s[idx:]
		if end := strings.IndexAny(s, " \t\r\n"); end >= 0 {
			s = s[:end]
		}
	} else {
		return E2EEClientOptions{}, errors.New("未识别到 froge2ee:// 链接")
	}
	u, err := url.Parse(s)
	if err != nil {
		return E2EEClientOptions{}, fmt.Errorf("无效的 E2EE 链接: %w", err)
	}
	if u.User == nil {
		return E2EEClientOptions{}, errors.New("E2EE 链接缺少设备密钥")
	}
	peerID := strings.ToLower(strings.TrimSpace(u.User.Username()))
	if b, err := hex.DecodeString(peerID); err != nil || len(b) != 8 {
		return E2EEClientOptions{}, errors.New("E2EE PeerID 无效")
	}
	pskRaw, _ := u.User.Password()
	var pskHex string
	if b, err := hex.DecodeString(pskRaw); err == nil && len(b) == 32 {
		pskHex = strings.ToLower(pskRaw)
	} else if b, err := decodeBase64Flexible(pskRaw); err == nil && len(b) == 32 {
		pskHex = hex.EncodeToString(b)
	} else {
		return E2EEClientOptions{}, errors.New("E2EE PSK 密钥无效")
	}
	hostID := strings.ToLower(strings.TrimSpace(u.Host))
	if len(hostID) < 8 {
		return E2EEClientOptions{}, errors.New("E2EE HostID 无效")
	}
	pub := strings.TrimSpace(u.Query().Get("pub"))
	pubBytes, err := decodeBase64Flexible(pub)
	if err != nil || len(pubBytes) != 32 {
		return E2EEClientOptions{}, errors.New("E2EE 公钥无效")
	}
	relayURL := strings.TrimSpace(u.Query().Get("relay"))
	lanAddr := strings.TrimSpace(u.Query().Get("lan"))
	if relayURL == "" && lanAddr == "" {
		return E2EEClientOptions{}, errors.New("E2EE 链接缺少中继或局域网地址")
	}
	name := strings.TrimSpace(u.Fragment)
	if dec, err := url.PathUnescape(name); err == nil && dec != "" {
		name = dec
	}
	return E2EEClientOptions{
		PeerIDHex:    peerID,
		PeerPSKHex:   pskHex,
		HostID:       hostID,
		ServerPubB64: base64.RawURLEncoding.EncodeToString(pubBytes),
		RelayURL:     relayURL,
		RelayToken:   strings.TrimSpace(u.Query().Get("rt")),
		LANAddr:      lanAddr,
		ServerName:   name,
	}, nil
}

// E2EEEnvelope is the ONLY JSON structure visible to the Blind Relay (Cloudflare Worker / VPS).
// All inner HTTP requests, headers, SSE streams, and payloads are AES-256-GCM encrypted in Ciphertext.
type E2EEEnvelope struct {
	To         string `json:"to"`           // "host" or "client:<peer_id>"
	From       string `json:"from"`         // "client:<peer_id>" or "host"
	EphPub     string `json:"ep"`           // 32-byte ephemeral X25519 pubkey (base64url raw) for forward secrecy
	Nonce      string `json:"n"`            // 12-byte AES-GCM nonce (base64url raw)
	Ciphertext string `json:"c"`            // AES-256-GCM ciphertext+tag (base64url raw)
	Err        string `json:"err,omitempty"` // relay-level error e.g. "host_offline"
}

// E2EEInnerFrame is the plaintext JSON multiplexed inside E2EEEnvelope.Ciphertext.
type E2EEInnerFrame struct {
	Type    string            `json:"t"`           // "req" | "resp" | "chunk" | "end" | "cancel" | "ping" | "pong"
	Stream  string            `json:"s,omitempty"` // unique per-request stream ID
	Method  string            `json:"m,omitempty"`
	Path    string            `json:"p,omitempty"`
	Headers map[string]string `json:"h,omitempty"`
	Status  int               `json:"st,omitempty"`
	BodyB64 string            `json:"b,omitempty"`
	EOF     bool              `json:"eof,omitempty"`
	Error   string            `json:"err,omitempty"`
}

// DeriveE2EESessionKey computes the shared 32-byte AES-256-GCM key identically across
// Go, Apple CryptoKit (iOS/macOS), Kotlin (Android), and WebCrypto:
//   shared = X25519(myPriv, peerPub)
//   ikm    = shared || psk (64 bytes)
//   key    = HKDF-SHA256(ikm, salt="frog-e2ee-v1", info=hostID+"|"+peerID, len=32)
func DeriveE2EESessionKey(myPriv *ecdh.PrivateKey, peerPubBytes, psk []byte, hostID, peerID string) ([]byte, error) {
	if len(peerPubBytes) != 32 || len(psk) != 32 {
		return nil, errors.New("invalid X25519 pubkey or PSK length")
	}
	peerPub, err := ecdh.X25519().NewPublicKey(peerPubBytes)
	if err != nil {
		return nil, err
	}
	shared, err := myPriv.ECDH(peerPub)
	if err != nil {
		return nil, err
	}
	ikm := make([]byte, 0, 64)
	ikm = append(ikm, shared...)
	ikm = append(ikm, psk...)

	info := []byte(hostID + "|" + peerID)
	r := hkdf.New(sha256.New, ikm, []byte(e2eeHKDFSalt), info)
	key := make([]byte, 32)
	if _, err := io.ReadFull(r, key); err != nil {
		return nil, err
	}
	return key, nil
}

// SealE2EE encrypts plaintext JSON into an opaque E2EEEnvelope bound to (from, to, ephPub) via AAD.
func SealE2EE(key []byte, from, to, ephPubB64 string, plaintext []byte) (E2EEEnvelope, error) {
	block, err := aes.NewCipher(key)
	if err != nil {
		return E2EEEnvelope{}, err
	}
	aead, err := cipher.NewGCM(block)
	if err != nil {
		return E2EEEnvelope{}, err
	}
	nonce := make([]byte, aead.NonceSize())
	if _, err := rand.Read(nonce); err != nil {
		return E2EEEnvelope{}, err
	}
	aad := []byte(from + "|" + to + "|" + ephPubB64)
	ct := aead.Seal(nil, nonce, plaintext, aad)
	return E2EEEnvelope{
		To:         to,
		From:       from,
		EphPub:     ephPubB64,
		Nonce:      base64.RawURLEncoding.EncodeToString(nonce),
		Ciphertext: base64.RawURLEncoding.EncodeToString(ct),
	}, nil
}

// OpenE2EE authenticates and decrypts an E2EEEnvelope.
func OpenE2EE(key []byte, env E2EEEnvelope) ([]byte, error) {
	block, err := aes.NewCipher(key)
	if err != nil {
		return nil, err
	}
	aead, err := cipher.NewGCM(block)
	if err != nil {
		return nil, err
	}
	nonce, err := decodeBase64Flexible(env.Nonce)
	if err != nil || len(nonce) != aead.NonceSize() {
		return nil, errors.New("invalid E2EE nonce")
	}
	ct, err := decodeBase64Flexible(env.Ciphertext)
	if err != nil {
		return nil, errors.New("invalid E2EE ciphertext")
	}
	aad := []byte(env.From + "|" + env.To + "|" + env.EphPub)
	pt, err := aead.Open(nil, nonce, ct, aad)
	if err != nil {
		return nil, errors.New("E2EE AES-GCM 解密校验失败")
	}
	return pt, nil
}
